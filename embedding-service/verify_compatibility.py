"""Numerical compatibility verification script for InLegalBERT microservice.

Compares embeddings generated by StandaloneInLegalBertEmbedder against the
existing PyTorch InLegalBertEmbedder in server/api/app/retrieval/embeddings.py.
Verifies cosine similarity, max absolute elementwise difference, and FAISS top-1/top-5 retrieval overlap.
"""

from __future__ import annotations

import importlib.util
import json
import logging
import sys
from pathlib import Path

import numpy as np

# Absolute file paths
SERVICE_DIR = Path(__file__).resolve().parent
REPO_ROOT = SERVICE_DIR.parent
SERVER_API_DIR = REPO_ROOT / "server" / "api"

# Ensure server/api is in sys.path for backend imports
if str(SERVER_API_DIR) not in sys.path:
    sys.path.insert(0, str(SERVER_API_DIR))

# Import StandaloneInLegalBertEmbedder directly from file with module registration
module_name = "standalone_embedder_module"
embedder_spec = importlib.util.spec_from_file_location(module_name, SERVICE_DIR / "app" / "embedder.py")
embedder_mod = importlib.util.module_from_spec(embedder_spec)
sys.modules[module_name] = embedder_mod
embedder_spec.loader.exec_module(embedder_mod)
StandaloneInLegalBertEmbedder = embedder_mod.StandaloneInLegalBertEmbedder
ServiceEmbedderConfig = embedder_mod.EmbedderConfig

# Import backend modules from server/api
from app.core.config import get_data_dir, get_settings
from app.retrieval.embeddings import EmbeddingConfig as PyTorchConfig, InLegalBertEmbedder as PyTorchInLegalBertEmbedder
from app.retrieval.index import load_index, search_index_rows

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("numerical_verification")

BENCHMARK_QUERIES = [
    "What does Article 21 protect?",
    "How has the Supreme Court interpreted Article 21?",
    "What is the relationship between Section 66A of the Information Technology Act and Article 19?",
    "What is the Basic Structure Doctrine?",
]


def run_numerical_compatibility_benchmark() -> dict:
    logger.info("Running Numerical Compatibility Benchmark...")

    # 1. Generate embeddings using existing backend PyTorch embedder
    logger.info("Generating embeddings via server/api PyTorch embedder...")
    pt_config = PyTorchConfig(model_name="law-ai/InLegalBERT", device="cpu", backend="pytorch")
    pt_embedder = PyTorchInLegalBertEmbedder(pt_config)
    pt_vectors = pt_embedder.embed(BENCHMARK_QUERIES)  # shape: (4, 768) float32

    # 2. Generate embeddings using new Standalone microservice embedder
    logger.info("Generating embeddings via embedding-service standalone embedder...")
    service_config = ServiceEmbedderConfig(model_name="law-ai/InLegalBERT", device="cpu")
    service_embedder = StandaloneInLegalBertEmbedder(service_config)
    service_vecs_list = service_embedder.embed(BENCHMARK_QUERIES)
    service_vectors = np.array(service_vecs_list, dtype=np.float32)

    # 3. Compute elementwise and cosine similarity metrics
    cosines = []
    abs_diffs = np.abs(pt_vectors - service_vectors)
    for i in range(len(BENCHMARK_QUERIES)):
        dot_product = np.dot(pt_vectors[i], service_vectors[i])
        norm_a = np.linalg.norm(pt_vectors[i])
        norm_b = np.linalg.norm(service_vectors[i])
        cosine_sim = float(dot_product / (norm_a * norm_b))
        cosines.append(cosine_sim)

    # 4. Perform FAISS Top-K retrieval comparison against production index
    settings = get_settings()
    data_dir = get_data_dir()
    faiss_index, metadata = load_index(data_dir, settings.vector_index_name)

    top1_matches = 0
    top5_matches = 0

    for i in range(len(BENCHMARK_QUERIES)):
        pt_hits = search_index_rows(faiss_index, metadata, pt_vectors[i : i + 1], top_k=5)
        service_hits = search_index_rows(faiss_index, metadata, service_vectors[i : i + 1], top_k=5)

        pt_top1 = pt_hits[0]["chunk_id"] if pt_hits else None
        service_top1 = service_hits[0]["chunk_id"] if service_hits else None
        if pt_top1 == service_top1:
            top1_matches += 1

        pt_top5_set = set(h["chunk_id"] for h in pt_hits)
        service_top5_set = set(h["chunk_id"] for h in service_hits)
        if pt_top5_set == service_top5_set:
            top5_matches += 1

    report = {
        "queries_tested": len(BENCHMARK_QUERIES),
        "vector_dimensions": list(service_vectors.shape),
        "dtype": str(service_vectors.dtype),
        "metrics": {
            "min_cosine_similarity": round(float(np.min(cosines)), 8),
            "mean_cosine_similarity": round(float(np.mean(cosines)), 8),
            "max_cosine_similarity": round(float(np.max(cosines)), 8),
            "mean_abs_difference": round(float(np.mean(abs_diffs)), 8),
            "max_abs_difference": round(float(np.max(abs_diffs)), 8),
        },
        "faiss_retrieval_parity": {
            "top1_match_rate": round(top1_matches / len(BENCHMARK_QUERIES), 4),
            "top5_exact_set_match_rate": round(top5_matches / len(BENCHMARK_QUERIES), 4),
        },
        "status": "PASS" if np.min(cosines) > 0.99999 and top1_matches == len(BENCHMARK_QUERIES) else "FAIL",
    }
    return report


if __name__ == "__main__":
    results = run_numerical_compatibility_benchmark()
    print(json.dumps(results, indent=2))
